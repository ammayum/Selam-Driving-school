import { chromium, expect } from '@playwright/test';
const base=process.argv[2];
if(!/^http:\/\/127\.0\.0\.1:\d+$/.test(base)) throw new Error('Isolated server required');
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1280,height:900}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'/login');
  await page.locator('input').first().fill('admin');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.locator('input[type="password"]').fill('Test-password-2026!');
  await page.getByRole('button',{name:'Login',exact:true}).click();
  await page.getByRole('navigation',{name:'Administration'}).getByRole('link',{name:'Website Content',exact:true}).click();
  const editor=page.getByRole('article').filter({has:page.getByRole('heading',{name:'Pages & Sections',exact:true})});
  await editor.getByLabel('Select page or section').selectOption('home_packages');
  await expect(editor.getByLabel('Title',{exact:true})).toHaveValue('Find your starting gear.');
  await editor.getByLabel('Title',{exact:true}).fill('Choose your driving hours');
  await editor.getByRole('button',{name:'Save Content',exact:true}).click();
  await expect(editor.getByRole('status')).toHaveText('Content saved.');
  await editor.getByLabel('Select page or section').selectOption('home');
  await editor.getByLabel('Select page or section').selectOption('home_packages');
  await expect(editor.getByLabel('Title',{exact:true})).toHaveValue('Choose your driving hours');
  const visitor=await browser.newPage({viewport:{width:390,height:844}});
  await visitor.goto(base+'/');
  await expect(visitor.getByRole('heading',{name:'Choose your driving hours',exact:true})).toBeVisible();
  await page.getByRole('navigation',{name:'Administration'}).getByRole('link',{name:'User Management',exact:true}).click();
  const adminRow=page.getByRole('row').filter({hasText:'admin@example.test'});
  await adminRow.getByRole('button',{name:'Reset password',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Your administrator password').fill('Test-password-2026!');
  await dialog.getByRole('button',{name:'Send Reset Email',exact:true}).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('status')).toContainText('Password reset email queued');
  await page.getByRole('button',{name:'Add User',exact:true}).click();
  await dialog.getByLabel('Full name').fill('Browser Managed');
  await dialog.getByLabel('Email',{exact:true}).fill('browser-managed@example.test');
  await dialog.getByLabel('Phone',{exact:true}).fill('07000000000');
  await dialog.getByRole('button',{name:'Create Account',exact:true}).click();
  await expect(dialog).not.toBeVisible();
  const credentials=page.getByRole('complementary',{name:'Temporary login details'});
  const temporary=await credentials.getByLabel('Temporary password',{exact:true}).inputValue();
  const username=await credentials.getByLabel('Username',{exact:true}).inputValue();
  await credentials.getByRole('button',{name:'I have saved the details',exact:true}).click();
  await expect(credentials).toHaveCount(0);
  const learner=await browser.newPage();
  await learner.goto(base+'/login');
  await learner.locator('input').first().fill(username);
  await learner.getByRole('button',{name:'Continue',exact:true}).click();
  await learner.locator('input[type="password"]').fill(temporary);
  await learner.getByRole('button',{name:'Login',exact:true}).click();
  await expect(learner).toHaveURL(base+'/change-password');
  await learner.getByLabel('Current or temporary password').fill(temporary);
  await learner.getByLabel('New password',{exact:true}).fill('Browser-new-password-2026!');
  await learner.getByLabel('Confirm new password',{exact:true}).fill('Browser-new-password-2026!');
  await learner.getByRole('button',{name:'Save New Password',exact:true}).click();
  await expect(learner).toHaveURL(base+'/portal');
  await learner.close();
  await page.getByLabel('Search users').fill('browser-managed@example.test');
  const managed=page.getByRole('row').filter({hasText:'browser-managed@example.test'});
  await expect(managed).toBeVisible();
  await managed.getByRole('button',{name:'Edit',exact:true}).click();
  await dialog.getByLabel('Full name').fill('Browser Updated');
  await dialog.getByRole('button',{name:'Save Changes',exact:true}).click();
  await expect(managed).toContainText('Browser Updated');
  await managed.getByRole('button',{name:'Freeze',exact:true}).click();
  await dialog.getByRole('button',{name:'Freeze account',exact:true}).click();
  await expect(managed.getByRole('button',{name:'Reset password',exact:true})).toBeDisabled();
  await managed.getByRole('button',{name:'Unfreeze',exact:true}).click();
  await dialog.getByRole('button',{name:'Unfreeze account',exact:true}).click();
  await expect(managed.getByRole('button',{name:'Reset password',exact:true})).toBeEnabled();
  await managed.getByRole('button',{name:'Delete',exact:true}).click();
  await expect(dialog).toContainText('Bookings and audit history will be kept.');
  await dialog.getByRole('button',{name:'Delete account',exact:true}).click();
  await expect(managed).toHaveCount(0);
  await page.getByLabel('Status',{exact:false}).selectOption('deleted');
  await managed.getByRole('button',{name:'Restore',exact:true}).click();
  await dialog.getByRole('button',{name:'Restore account',exact:true}).click();
  await expect(managed).toHaveCount(0);
  await page.getByLabel('Status',{exact:false}).selectOption('current');
  await expect(managed).toContainText('Active');
  await page.getByLabel('Search users').fill('');
  await page.screenshot({path:'../docs/user-management-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'../docs/user-management-mobile.png',fullPage:true});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)) throw new Error('User management mobile overflow');
  await page.getByRole('navigation',{name:'Administration'}).getByRole('link',{name:'Website Content',exact:true}).click();
  await editor.getByLabel('Select page or section').selectOption('home_packages');
  await editor.screenshot({path:'../docs/cms-manager-mobile.png'});
  if(errors.length) throw new Error(errors.join('\n'));
  console.log('PASS browser CMS editor loading/persistence/public display and admin reset form.');
} finally { await browser.close(); }
