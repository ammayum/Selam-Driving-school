import { chromium, expect } from '@playwright/test';
const base=process.argv[2];
if(!/^http:\/\/127\.0\.0\.1:\d+$/.test(base)) throw new Error('Isolated server required');
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
  const page=await browser.newPage({viewport:{width:1366,height:900}});
  const errors=[]; page.on('pageerror',error=>errors.push(error.message));
  await page.goto(base+'/login');
  await page.locator('input').first().fill('admin');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.locator('input[type="password"]').fill('Test-password-2026!');
  await page.getByRole('button',{name:'Login',exact:true}).click();
  await expect(page).toHaveURL(base+'/admin/overview');
  await page.getByRole('navigation',{name:'Administration'}).getByRole('link',{name:'Website Content'}).click();
  await page.getByRole('navigation',{name:'Website pages'}).getByRole('link',{name:'Notifications',exact:true}).click();
  await page.getByLabel('Email subject').fill('CMS test: {{subject}}');
  await page.getByLabel('Email message').fill('Welcome to {{site_name}}\n{{details}}');
  await page.getByRole('button',{name:'Save Notification Template'}).click();
  await expect(page.getByRole('status').filter({hasText:'Notification template saved.'})).toBeVisible();
  await page.reload();
  await expect(page.getByLabel('Email subject')).toHaveValue('CMS test: {{subject}}');
  await page.getByRole('navigation',{name:'Website pages'}).getByRole('link',{name:'Header & Footer'}).click();
  await page.getByLabel('Select page or section').selectOption('copy_site_about');
  await page.getByLabel('Displayed text').fill('Our School');
  await page.getByRole('button',{name:'Save Content',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Content saved.'})).toBeVisible();
  await page.reload();
  await expect(page).toHaveURL(base+'/admin/cms/site');
  await expect(page.getByRole('heading',{name:'Public Contact Details'})).toBeVisible();
  await page.getByRole('navigation',{name:'Website pages'}).getByRole('link',{name:'Book',exact:true}).click();
  await page.getByLabel('Select page or section').selectOption('book_request');
  await page.getByLabel('Title',{exact:true}).fill('Plan your first lesson');
  await page.getByRole('button',{name:'Save Content',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Content saved.'})).toBeVisible();
  await page.getByRole('navigation',{name:'Administration'}).getByRole('link',{name:'User Management'}).click();
  await expect(page).toHaveURL(base+'/admin/users');
  await page.goBack();
  await expect(page).toHaveURL(base+'/admin/cms/book');
  await page.reload();
  await expect(page.getByLabel('Select page or section')).toBeVisible();
  await page.screenshot({path:'../storage/admin-pages-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'../storage/admin-pages-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  const visitor=await browser.newPage({viewport:{width:390,height:844}});
  await visitor.goto(base+'/book');
  await expect(visitor.getByRole('heading',{name:'Plan your first lesson'})).toBeVisible();
  await visitor.getByRole('button',{name:'Toggle navigation menu'}).click();
  await expect(visitor.getByRole('link',{name:'Our School',exact:true})).toBeVisible();
  await visitor.goto(base+'/admin/cms/home');
  await expect(visitor.getByRole('heading',{name:'Portal access required'})).toBeVisible();
  await visitor.goto(base+'/login');
  await visitor.locator('input').first().fill('student');
  await visitor.getByRole('button',{name:'Continue',exact:true}).click();
  await visitor.locator('input[type="password"]').fill('Test-password-2026!');
  await visitor.getByRole('button',{name:'Login',exact:true}).click();
  await expect(visitor).toHaveURL(base+'/portal');
  await visitor.goto(base+'/admin/cms/home');
  await expect(visitor.getByRole('heading',{name:'Administrator access required'})).toBeVisible();
  expect(errors).toEqual([]);
  console.log('PASS browser: admin routes, reload/back, CMS editing, published copy, mobile fit and role guards.');
} finally { await browser.close(); }
