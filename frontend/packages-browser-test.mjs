import { chromium, expect } from '@playwright/test';
const base = process.argv[2];
if (!/^http:\/\/127\.0\.0\.1:\d+$/.test(base)) throw new Error('Isolated server required');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto(base+'/login');
  await page.locator('input').first().fill('admin');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.locator('input[type="password"]').fill('Test-password-2026!');
  await page.getByRole('button',{name:'Login',exact:true}).click();
  await page.getByRole('button',{name:'Packages',exact:true}).click();
  const form=page.locator('form').filter({has:page.getByRole('button',{name:'Create Package',exact:true})});
  await form.locator('input').first().fill('Browser automatic hours');
  await form.getByLabel('Type',{exact:true}).selectOption('automatic');
  await form.getByLabel('Hours',{exact:true}).fill('4.5');
  await form.locator('input[type="number"]').nth(1).fill('180');
  await form.getByRole('button',{name:'Create Package',exact:true}).click();
  const row=page.getByRole('row').filter({hasText:'Browser automatic hours'});
  await expect(row).toContainText('Automatic'); await expect(row).toContainText('4.5');
  await row.getByRole('button',{name:'Edit',exact:true}).click();
  await expect(page.getByLabel('Hours',{exact:true})).toHaveValue('4.5');
  await expect(page.getByLabel('Type',{exact:true})).toHaveValue('automatic');
  await page.getByLabel('Hours',{exact:true}).fill('5.5');
  await page.getByRole('button',{name:'Update Package',exact:true}).click();
  await expect(row).toContainText('5.5');
  await page.screenshot({path:'../docs/packages-hours-admin.png',fullPage:true});
  const visitor=await browser.newPage({viewport:{width:390,height:844}});
  visitor.on('pageerror',e=>errors.push(e.message));
  await visitor.goto(base+'/');
  const showcase=visitor.locator('.package-showcase');
  await expect(showcase.locator('.package-pass')).toHaveCount(5);
  await showcase.getByRole('button',{name:'Automatic',exact:true}).click();
  await expect(showcase.locator('.package-pass')).toHaveCount(3);
  await expect(showcase).not.toContainText('Legacy Manual');
  await showcase.screenshot({animations:'disabled',path:'../docs/home-packages-mobile.png'});
  if(await visitor.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)) throw new Error('Homepage mobile overflow');
  await visitor.setViewportSize({width:1440,height:1000});
  await showcase.getByRole('button',{name:'All packages',exact:true}).click();
  await showcase.screenshot({animations:'disabled',path:'../docs/home-packages-desktop.png'});
  await showcase.getByRole('link',{name:'Choose Browser automatic hours, automatic, 5.5 hours',exact:true}).click();
  await expect(visitor.getByLabel('Lesson type',{exact:true})).toHaveValue('automatic');
  await expect(visitor.getByLabel('Package',{exact:true}).locator('option:checked')).toContainText('Browser automatic hours');
  await visitor.setViewportSize({width:390,height:844});
  await visitor.goto(base+'/book');
  const packages=visitor.getByLabel('Package',{exact:true});
  await expect(packages.locator('option')).toContainText(['Select package','Legacy Manual','Manual Hours']);
  await packages.selectOption({label:'Manual Hours - 2.5 hours - GBP 90'});
  await visitor.getByLabel('Lesson type',{exact:true}).selectOption('automatic');
  await expect(packages).toHaveValue('');
  await expect(packages.locator('option')).toHaveCount(4);
  await expect(packages).not.toContainText('Manual Hours');
  await packages.selectOption({label:'Browser automatic hours - 5.5 hours - GBP 180'});
  await expect(visitor.getByText('5.5 hours included.',{exact:true})).toBeVisible();
  await visitor.screenshot({path:'../docs/packages-filter-mobile.png',fullPage:true});
  await visitor.locator('[name="preferred_start"]').fill('2028-02-01T10:00');
  await visitor.locator('[name="pickup_location"]').fill('Sheffield');
  await visitor.locator('[name="guest_name"]').fill('Package Test');
  await visitor.locator('[name="guest_email"]').fill('package-test@example.test');
  await visitor.locator('[name="guest_phone"]').fill('07000000000');
  await visitor.getByRole('button',{name:'Submit Booking',exact:true}).click();
  await expect(visitor.getByText('Booking submitted. We will be in contact with your lesson details and assigned instructor.',{exact:true})).toBeVisible();
  if(await visitor.evaluate(()=>document.documentElement.scrollWidth>innerWidth+2)) throw new Error('Mobile overflow');
  if(errors.length) throw new Error(errors.join('\n'));
  console.log('PASS browser packages: create/edit automatic fractional hours, type filtering/reset, mobile booking submission.');
} finally { await browser.close(); }

